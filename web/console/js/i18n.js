export function t(key, fallback = "") {
  const table = MESSAGES[store.locale] || MESSAGES.en;
  return table[key] ?? MESSAGES.en[key] ?? fallback ?? key;
}

export function setLocale(locale) {
  store.locale = locale === "zh" ? "zh" : "en";
  try { localStorage.setItem("webscan-console-locale-v1", store.locale); } catch { /* ignore */ }
}

export function toggleLocale() {
  setLocale(store.locale === "zh" ? "en" : "zh");
}

export function currentLocale() {
  return store.locale;
}
